#!/usr/bin/env python3
"""Run a GP-50 feature component (ABI 3) and its tests on this computer.

    python3 sdk/nds/components/native/run_native.py <component folder> [--cc cc]

Compiles the component's sources, every test_*.c in its folder, the native platform (gp50_native.c) and a generated
callback table with the computer's C compiler, then runs the result. Exit status 0 = all checks passed.
Manifest validation here is the same one the pedal build uses (scripts/nds_ui/components.py).
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
COMPONENTS = HERE.parent
ROOT = COMPONENTS.parents[2]
sys.path.insert(0, str(ROOT / 'scripts'))
from nds_ui.components import discover_one, ABI3_CALLBACKS  # noqa: E402

FORMS = {
    'init': 'void (*{r})(const gp50_ctx *)', 'tick': 'void (*{r})(const gp50_ctx *)',
    'get': 'uint32_t (*{r})(const gp50_ctx *, uint8_t *, uint32_t)',
    'set': 'uint32_t (*{r})(const gp50_ctx *, const uint8_t *, uint32_t)',
    'event': 'uint32_t (*{r})(const gp50_ctx *, const gp50_event *)',
    'status': 'uint32_t (*{r})(const gp50_ctx *, char *, uint32_t)',
    'preset_save': 'uint32_t (*{r})(const gp50_ctx *, uint8_t *, uint32_t)',
    'preset_load': 'void (*{r})(const gp50_ctx *, const uint8_t *, uint32_t)',
    'menu_value': 'uint32_t (*{r})(const gp50_ctx *, uint32_t, char *, uint32_t)',
    'menu_change': 'uint32_t (*{r})(const gp50_ctx *, uint32_t, int32_t)',
    'about': 'uint32_t (*{r})(const gp50_ctx *, char *, uint32_t)',
    'strip': 'uint32_t (*{r})(const gp50_ctx *, uint32_t, gp50_strip *)',
}


def component_header(m):
    host = m['host'] or {'set_bytes': 0, 'max_reply_bytes': 1}
    cb = m['callbacks']
    lines = ['/* Generated by run_native.py. */', '#include "gp50.h"']
    lines += [FORMS[r].format(r='').replace('(*)', cb[r]) + ';' for r in ABI3_CALLBACKS if cb.get(r)]
    lines += ['typedef struct {'] + ['    ' + FORMS[r].format(r=r) + ';' for r in ABI3_CALLBACKS] + ['} gp50_native_descriptor;']
    lines.append('static const gp50_native_descriptor GP50_NATIVE_COMPONENT = { '
                 + ', '.join(cb.get(r) or '0' for r in ABI3_CALLBACKS) + ' };')
    lines += [f'#define GP50_NATIVE_STATE_BYTES {m["resources"]["state_bytes"]}u',
              f'#define GP50_NATIVE_SET_BYTES {host["set_bytes"]}u',
              f'#define GP50_NATIVE_MAX_REPLY {host["max_reply_bytes"]}u',
              f'#define GP50_NATIVE_PRESET_DATA {m.get("preset_bytes", 0)}u',
              f'#define GP50_NATIVE_MENU_ITEMS {len((m.get("menu") or {}).get("items", []))}u']
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('component')
    ap.add_argument('--cc', default='cc')
    a = ap.parse_args()
    folder = Path(a.component).resolve()
    m = discover_one(folder / 'component.json', folder)
    if m['abi'] != 3:
        sys.exit('run_native.py runs ABI 3 feature components')
    tests = sorted(folder.glob('test_*.c'))
    if not tests:
        sys.exit(f'no test_*.c in {folder}')
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp / 'gp50_native_component.h').write_text(component_header(m))
        exe = tmp / 'feature_test'
        cmd = [a.cc, '-std=c99', '-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter', '-O1', '-g',
               '-I', str(COMPONENTS), '-I', str(HERE), '-I', str(tmp), '-I', str(folder),
               *[str(folder / s) for s in m['source_names']], *map(str, tests), str(HERE / 'gp50_native.c'), '-o', str(exe)]
        r = subprocess.run(cmd)
        if r.returncode:
            sys.exit(f'compile failed ({r.returncode})')
        try:
            sys.exit(subprocess.run([str(exe)], timeout=30).returncode)
        except subprocess.TimeoutExpired:
            sys.exit('test run did not finish in 30 s (a loop that never ends?)')


if __name__ == '__main__':
    main()
