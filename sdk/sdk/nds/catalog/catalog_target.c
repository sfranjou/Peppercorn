/* The group-4/9 bridge services call the stock slot-table entries by address on purpose: those entries are
 * hook sites (redirected to the wrappers below), so they are not callable stock-API functions. */
typedef uint32_t (*stock_u0_t)(void);
typedef uint32_t (*stock_u1_t)(uint32_t);
#define STOCK(type, addr) ((type)(uintptr_t)(addr))

