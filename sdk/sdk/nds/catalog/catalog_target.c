/* Names, flat (one descriptor lookup; stack close to stock). String pool: for our descriptors right after their own
 * parameter records; for stock entries the stock formula through region e's directory with the caller's ordinal
 * (reconstructed string_pool, catalog_accessors.c; equivalence: scripts/verify_nds_own_catalog.py). */
static uint32_t name_pool(uint32_t g, uint32_t o, const uint8_t *d) {
    const uint8_t *own = own_entry(g, o, &IO.memory);
    uint32_t base = own ? (uint32_t)(uintptr_t)own
                        : CATALOG + r32(&IO, CATALOG + 4 + r32(&IO, r32(&IO, DIRECTORY) + 0x14 + 4 * g) + 4 * o);
    return base + 0x10 + 24u * d[8];
}
uint32_t nds_cat_197ca(uint32_t g, uint32_t o, uint32_t dst, uint32_t n) {
    const uint8_t *d = (const uint8_t *)(uintptr_t)own_descriptor(g, o, &IO.memory);
    if (!d) { copy_string(&IO, dst, EFFECT_NAME_FALLBACK, n); return 1; }
    copy_string(&IO, dst, name_pool(g, o, d) + (d[0xc] | d[0xd] << 8), n); return 0;
}
uint32_t nds_cat_1982e(uint32_t g, uint32_t o, uint32_t p, uint32_t dst, uint32_t n) {
    const uint8_t *d = (const uint8_t *)(uintptr_t)own_descriptor(g, o, &IO.memory);
    if (!d || p >= d[8]) { copy_string(&IO, dst, PARAMETER_NAME_FALLBACK, n); return 1; }
    const uint8_t *r = d + 0x12 + 24 * p; copy_string(&IO, dst, name_pool(g, o, d) + (r[0] | r[1] << 8), n); return 0;
}
