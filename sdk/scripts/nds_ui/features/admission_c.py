def c_headers(cfg=None, parent_b=None):
    tbl = AC.table()[0]
    rows = []
    for g in AC.ARM_GROUPS:
        rows.append(f'static const struct adm_row adm_rows{g}[] = {{' + ', '.join(f'{{{i:#010x}u, {c}u}}' for i, c in tbl[g]) + '};')
    groups = ', '.join(f'{{{g}u, {len(tbl[g])}u, adm_rows{g}}}' for g in AC.ARM_GROUPS)
    dsp = '#define ADM_WITH_DSP 0\n'
    if AC.with_dsp():   # table v4+: coprocessor rows (DST/AMP/EQ) and constants
        dt = AC.dsp_table()
        dsp = '#define ADM_WITH_DSP 1\n' + ''.join(f'#define ADM_DSP_{k} {v}u\n' for k, v in (('BASE', AC.DSP_BASE), ('UNKNOWN', AC.DSP_UNKNOWN), ('CAB', AC.DSP_CAB), ('NTOS', AC.dsp_ntos())))
        dsp += ''.join('static const struct adm_row adm_dsp_rows%d[] = {%s};\n' % (g, ', '.join(f'{{{i:#010x}u, {c}u}}' for i, c in dt[g])) for g in (2, 3, 5))
        dsp += 'static const struct adm_group adm_dsp_groups[] = {' + ', '.join(f'{{{g}u, {len(dt[g])}u, adm_dsp_rows{g}}}' for g in (2, 3, 5)) + '};\n'
    # v6+: capture-pair refusal rules (emitted only then, so v1..v5 headers stay byte-identical)
    capture = (f'#define ADM_CAPTURE_RULES 1\n#define ADM_DST_CAPTURE_ID {AC.DST_CAPTURE_ID:#010x}u\n' if AC.capture_rules() else '')
    if AC.capture_force(): capture += f'#define ADM_CAPTURE_FORCE 1\n#define ADM_CAPTURE_MAIN_OFF {AC.CAPTURE_MAIN_OFF:#010x}u\n'
    headers = {'admission_table.h': f'''/* GENERATED by scripts/nds_ui/features/admission_c.py from sdk/telemetry/nds/admission_costs.py. */
#ifndef ADMISSION_TABLE_H
#define ADMISSION_TABLE_H
#include <stdint.h>
#define ADM_BASE {AC.BASE}u
#define ADM_UNKNOWN {AC.UNKNOWN}u
#define ADM_WARN_PCT {WARN_PCT}u
#define ADM_ARM_RAW_FULL {asm_admission.ARM_RAW_FULL}u
#define ADM_PING_PONG_ID {AC.PING_PONG_ID:#010x}u
#define ADM_PING_PONG_COST {dict(tbl[7])[AC.PING_PONG_ID]}u
#define ADM_STATE_WARN {STATE_WARN_WORD}
#define ADM_STATE_KEY {STATE_KEY_WORD}
#define ADM_GROUPS {len(AC.ARM_GROUPS)}u
#define ADM_WITH_REFUSAL {int('refuse_c' in ((cfg or {}).get('features') or ()))}
{capture}struct adm_row {{ uint32_t id, cost; }};
struct adm_group {{ uint32_t group, count; const struct adm_row *rows; }};
{chr(10).join(rows)}
static const struct adm_group adm_groups[] = {{{groups}}};
{dsp}#endif
'''}

    if (cfg or {}).get('c_shared_admission_tables'):
        # The two modules consume identical generated immutable tables. Weak
        # definitions coalesce by name, including all group-pointer relocations.
        # Canonical per-feature links retain a complete copy for module audits.
        headers['admission_table.h'] = headers['admission_table.h'].replace(
            'static const struct adm_', '__attribute__((weak)) const struct adm_')
    return headers


def hook_home_arm_text(c):
    # Only ARM mode (s3 == 1) gets the CPU text; a1 must point at the finished buffer afterwards.
    c.s.emit('movi a0,1\nbne s3,a0,@ui_set\nmov55 a0,s8\nmov55 a1,s7\naddi a2,sp,80\njal @nds_cpu_home_text\naddi a1,sp,80')


def hook_edit_strip(c):
    c.s.emit('lwi a1,[s0 + 0xe0]\nbeqz a1,@gr_done\nmov55 a0,s0\nmov55 a2,s1\njal @nds_cpu_edit_strip\nj @gr_done')


