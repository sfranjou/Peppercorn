"""Admission refusal in C (sdk/nds/ui/refuse.c): a block/model change that would raise the
predicted ARM load to REFUSE_PCT % or more is made a no-op, and the edit page shows
"CPU FULL NN%" for SHOW_TICKS (and so does the home title label). Three one-jal patches at the stock choke points (stock_api
hook_enable_get_call / hook_select_apply_call / hook_footswitch_call); every caller keeps its
register contract because the gates have the replaced routines' signatures.
Design: analysis/firmware/ADMISSION_REFUSAL.md. Oracle: sdk/telemetry/nds/model_refuse.py."""
from ..stock_api import API
from . import admission_c

NAME = 'refuse_c'
PROVIDES = 'refuse'
CONFLICTS = ()
REQUIRES = ('admission',)
ORACLES = ('sdk/telemetry/nds/model_refuse.py',)
CASE_KINDS = ('enable_gate', 'select_gate', 'footswitch_gate')
C_SOURCES = ('sdk/nds/ui/refuse.c',)
C_ENTRIES = ('nds_adm_enable_get', 'nds_adm_select_apply', 'nds_adm_footswitch', 'nds_refuse_strip')
REFUSE = 1000                 # thousandths: predicted 100 %; inferred overrun ~106 %, ghost overlay <= ~2.6 %
SHOW_TICKS = 2000             # application ticks (ms) the edit page shows CPU FULL
STATE_REFUSE_TICK, STATE_REFUSE_KEY, STATE_HOME_SHOWN = 37, 38, 39    # state +148/+152/+156 (state 160 B = bound 0x2001f540)


def c_headers(cfg=None, parent_b=None):
    seg = cfg['segment']
    home = bool(cfg.get('refusal_home'))   # MOD043+: message on the home title too (MOD042: edit page only)
    if seg['state_bytes'] < 4 * ((STATE_HOME_SHOWN if home else STATE_REFUSE_KEY) + 1): raise ValueError('refuse_c state too small')
    # admission_table.h too: the canonical per-module compile sees only this feature's headers
    return {**admission_c.c_headers(cfg, parent_b), 'refuse_table.h': f'''/* GENERATED by scripts/nds_ui/features/refuse_c.py. */
#ifndef REFUSE_TABLE_H
#define REFUSE_TABLE_H
#define NDS_UI_STATE {int(seg['state'], 16):#x}u
#define ADM_REFUSE {REFUSE}u
#define ADM_REFUSE_SHOW {SHOW_TICKS}u
#define ADM_STATE_REFUSE_TICK {STATE_REFUSE_TICK}
#define ADM_STATE_REFUSE_KEY {STATE_REFUSE_KEY}
#define ADM_STATE_HOME_SHOWN {STATE_HOME_SHOWN}
#define ADM_REFUSE_HOME {int(home)}
{_force_defines()}#endif
'''}


def _force_defines():
    from sdk.telemetry.nds import admission_costs as AC
    return (f'#define ADM_CAPTURE_FORCE 1\n#define ADM_DST_CAPTURE_ID {AC.DST_CAPTURE_ID:#010x}u\n#define ADM_CAPTURE_MAIN_OFF {AC.CAPTURE_MAIN_OFF:#010x}u\n'
            if AC.capture_force() else '')


def _force():
    from sdk.telemetry.nds import admission_costs as AC
    return AC.capture_force()


# v7 (2026-11-09): link filter for a DST capture with N->S off (sdk/nds/ui/dst_capture_link.c gp50_link_filter, a v7-only source of this feature). Stock calls of
# link_queue_produce (0x15480) in the four producers; stock bytes verified before patching.
LINK_SITES = ((0x463de, '49fe7851', 'full config 0x46366'), (0x466a2, '49fe76ef', 'enable 0x46678'),
              (0x4666e, '49fe7709', 'mask 0x4664c'), (0x46746, '49fe769d', 'model 0x466fe'))


def c_sources(cfg):
    return C_SOURCES + (('sdk/nds/ui/dst_capture_link.c',) if _force() else ())


def c_entries(cfg):
    # nds_refuse_home is called only from mem_page.c; it must be a root here so the canonical module
    # hash (refuse_c compiled alone, gc-sections) covers it (found 2026-10-20 by a mutation that the cache missed).
    return C_ENTRIES + (('gp50_enable_constraints',) if 'GP50_FEATURE_ENABLE_CONSTRAINTS=1' in (cfg or {}).get('c_defines', ()) else ()) + (('nds_refuse_home',) if (cfg or {}).get('refusal_home') else ()) + (('gp50_link_filter',) if _force() else ())


CODE = {}
DATA = {}
HOOKS = {}


def patches(c):
    L = c.labels
    out = [(API.hook_enable_get_call, f'jal {L["nds_adm_enable_get"]:#x}', '0x473f0 enable path: gate before the unchanged test'),
            (API.hook_select_apply_call, f'jal {L["nds_adm_select_apply"]:#x}', '0x475d8 selection path: gate replaces apply'),
            (API.hook_footswitch_call, f'jal {L["nds_adm_footswitch"]:#x}', '0x47452 footswitch path: gate wraps the toggle')]

    if _force():
        for at, old, what in LINK_SITES:
            if c.parent_b[at - 0x10000:at - 0x10000 + 4] != bytes.fromhex(old): raise ValueError('link producer call preimage mismatch at %#x' % at)
            out.append((at, f'jal {L["gp50_link_filter"]:#x}', what + ': DST capture keeps N->S loaded toward the ARM (v7)'))
        assert [API.hook_link_full_config_call, API.hook_link_enable_call, API.hook_link_mask_call, API.hook_link_model_call] == [x[0] for x in LINK_SITES]
    from ..stock_in_place import bulk_stems
    if 'application_bulk_c' in c.enabled and 'ui_footswitch' in bulk_stems(c.cfg):
        # stock_in_place: the stock press body is live again. With A/B footswitches the press goes through
        # gp50_fs_ab_press (A/B gate, then nds_adm_footswitch), exactly as the compiled press did.
        if 'GP50_FS_AB=1' in c.cfg.get('c_defines', ()):
            out[2] = (API.hook_footswitch_call, f'jal {L["gp50_fs_ab_press"]:#x}', '0x47452 footswitch path: A/B gate then admission gate')
        return out
    return [p for p in out if not ('application_bulk_c' in c.enabled and p[0] == API.hook_footswitch_call)]


def layout_info():
    return dict(refuse_thousandths=REFUSE, show_ticks=SHOW_TICKS, state_words=[STATE_REFUSE_TICK, STATE_REFUSE_KEY],
                implementation='C (sdk/nds/ui/refuse.c)')
