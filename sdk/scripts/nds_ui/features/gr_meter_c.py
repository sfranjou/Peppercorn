def patches(c):
    L = c.labels
    return [(API.hook_window4_tick, f'j {L["nds_gr_editor_tick"]:#x}', 'window 4 tick: GR meter (C), then MOD026 editor tick'),
            (API.hook_window4_close, f'j {L["gr_close"]:#x}', 'window 4 close: drop meter pointer, then MOD026 close')]


