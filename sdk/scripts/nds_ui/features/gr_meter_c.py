GR_COMP_ID = 0x01000041   # GR Comp public ID (appended to PRE)


def gr_ordinal(cfg=None):
    """GR Comp's PRE ordinal in the catalog this config builds (the meter shows only on that ordinal). Derived from the
    selected catalog extension, never assumed: the release set drops research PRE entries, which moves GR Comp
    (a fixed 15 hid the meter from MOD114 to MOD131)."""
    ext = (cfg or {}).get('catalog_ext')
    if not ext:
        return asm_gr.GR_ORDINAL   # configs without the own catalog: the MOD033 layout
    import json
    from ..build import ROOT
    import build_catalog_ext as X
    from protocol.overlay_image import parse_descriptor
    logical = X.resolve(json.loads((ROOT / ext['extension']).read_text()), (ROOT / 'work/v110/decoded_e.bin').read_bytes())
    ids = [parse_descriptor(d).public_id for d in logical[1]]
    if GR_COMP_ID not in ids and 'GP50_FEATURE_GR_METER=1' in (cfg or {}).get('c_defines', ()):
        return 0xff   # GR Comp left out of the image: the ordinal path is compiled out (feature strips draw the stock meters)
    if GR_COMP_ID not in ids:
        raise ValueError('GR Comp (0x01000041) is not in this PRE catalog: the GR meter could never show')
    return ids.index(GR_COMP_ID)


