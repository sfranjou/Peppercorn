"""Telemetry transport in C (sdk/nds/ui/telemetry.c): fifth C port, behaviour identical to the
asm `telemetry` (PROVIDES='telemetry'; service/receive/host/GUI cases + 66,816 routes).
Asm stubs that need the stock receiver's live registers stay: `dispatch`, `read_route`, and the
`receive` wrapper (saves s0..s8/lp, calls nds_receive(count = s0), tail-jumps to the stock
receiver continuation). `gui`, `service`, `host` and `read_table` are C with their asm names."""
import struct
from ..stock_api import API
from . import telemetry as asm_tel

NAME = 'telemetry_c'
PROVIDES = 'telemetry'
CONFLICTS = ('telemetry',)
REQUIRES = ()
ORACLES = asm_tel.ORACLES
CASE_KINDS = asm_tel.CASE_KINDS
C_SOURCES = ('sdk/nds/ui/telemetry.c',)
C_ENTRIES = ('gui', 'service', 'host', 'nds_receive', 'read_table')


def c_headers(cfg=None, parent_b=None):
    seg = cfg['segment']; off = API.host_read_table - 0x10000
    words = struct.unpack('<12I', parent_b[off:off + 48])
    return {'telemetry_table.h': f'''/* GENERATED by scripts/nds_ui/features/telemetry_c.py (stock read table from the parent image). */
#ifndef TELEMETRY_TABLE_H
#define TELEMETRY_TABLE_H
#define NDS_UI_STATE {int(seg['state'], 16):#x}u
#define NDS_UI_LEGACY {int(seg['legacy_cache'], 16):#x}u
#define HOST_READ_TABLE_STOCK {', '.join(f'{w:#010x}u' for w in words)}
#endif
'''}


def section_receive_stub(c):
    s = c.s
    c.begin('receive'); s.emit('mov55 a0,s0\njal @nds_receive'); c.end(tail=API.receive_continue)


def _host_layer(c):
    return 'host_layer_c' in (c.cfg.get('features') or ())


def section_read_route(c):
    """MOD056+ (host_layer_c): the parser 0x43374 and its read table are C; the `12 51` route lives in host_parse's
    HOST_OWN_GET hook (sdk/nds/host_layer/own_commands.c) and the table in own_read_table."""
    if not _host_layer(c): asm_tel.section_read_route(c)


def c_entries(cfg):
    """MOD056+ (host_layer_c): read_table is replaced by host_layer_c's own_read_table; not a GC root, so it is dropped."""
    entries = tuple(e for e in C_ENTRIES if e != 'read_table' or 'host_layer_c' not in ((cfg or {}).get('features') or ()))
    if 'capture_status_c' in ((cfg or {}).get('features') or ()):
        entries += ('gp50_capture_transport_reset', 'gp50_capture_display_frame')
    return entries


def section_dispatch(c):
    """MOD056+ (diagnostics_c): the legacy 0x6002 path continues at the feature's byte-faithful dispatch stub instead of
    the old block's 0x16c6e6 (API.mod030_dispatch)."""
    if 'diagnostics_c' not in (c.cfg.get('features') or ()): return asm_tel.section_dispatch(c)
    s = c.s
    s.label('dispatch'); s.emit('movi a0,0x60f0\nbeq a0,a5,@receive\nj @diag_dispatch_asm')


CODE = {'dispatch': section_dispatch, 'read_route': section_read_route, 'receive': section_receive_stub}
DATA = {}
HOOKS = {}


def patches(c):
    if not _host_layer(c): return asm_tel.patches(c)
    L = c.labels   # MOD056+: read route and read table are host_layer_c's (the bodies holding 0x4357a / 0x429ce are C)
    out = [(API.hook_gui_receive_call, f'jal {L["gui"]:#x}', 'GUI tick: wrapper calls stock receive then service'),
            (API.hook_link_dispatch, f'j {L["dispatch"]:#x}', 'receiver command compare: 0x60f0 to own receive')]

    from ..stock_in_place import bulk_stems   # the call site lives in bulk ui_tasks: live again when that module runs as stock
    return [p for p in out if not ('application_bulk_c' in c.enabled and p[0] == API.hook_gui_receive_call and 'ui_tasks' not in bulk_stems(c.cfg))]


def c_sources(cfg=None):
    """Paired capture successor selects one owner; default sources stay unchanged."""
    if "capture_status_c" not in ((cfg or {}).get("features") or ()):
        return C_SOURCES
    return tuple('sdk/capture_status/nds_telemetry.c' if src == 'sdk/nds/ui/telemetry.c' else src for src in C_SOURCES)
